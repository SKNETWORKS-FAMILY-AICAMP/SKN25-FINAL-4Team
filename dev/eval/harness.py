def _make_client(provider: str) -> OpenAI:
    if provider == "ollama":
        return OpenAI(base_url=OLLAMA_URL, api_key="ollama")
    if provider == "gemini":
        return OpenAI(
            api_key=os.getenv("GEMINI_API_KEY"),
            base_url="https://generativelanguage.googleapis.com/v1beta/openai/",
        )
    return OpenAI(api_key=os.getenv("OPENAI_API_KEY"))


def _uses_completion_tokens(model: str) -> bool:
    """gpt-5+ / o-시리즈는 max_tokens 대신 max_completion_tokens를 사용."""
    return model.startswith("gpt-5") or model.startswith("o1") or model.startswith("o3") or model.startswith("o4")


def _call(client: OpenAI, model: str, messages: list, max_tokens=3000) -> tuple[str, float]:
    # gpt-5+ 계열은 추론 토큰이 max_completion_tokens 예산을 소진하므로 여유 있게 설정
    if _uses_completion_tokens(model):
        max_tokens = max(max_tokens, 8000)
    t0 = time.time()
    # Ollama: 네이티브 API로 thinking 제어 (OpenAI-compat은 thinking 토큰이 max_tokens를 소진)
    if PROVIDER == "ollama" and client.base_url and "11434" in str(client.base_url):
        import httpx
        base = str(client.base_url).rstrip("/").removesuffix("/v1")
        payload = {
            "model": model,
            "messages": messages,
            "stream": False,
            "think": False,  # 하니스는 순수 응답 품질 평가 — thinking 없이 측정
            "options": {"num_predict": max_tokens},
        }
        r = httpx.post(f"{base}/api/chat", json=payload, timeout=300)
        r.raise_for_status()
        msg = r.json()["message"]
        content = msg.get("content") or msg.get("thinking", "")
        elapsed = round((time.time() - t0) * 1000)
        return content, elapsed
    token_kwargs = ({"max_completion_tokens": max_tokens} if _uses_completion_tokens(model)
                    else {"max_tokens": max_tokens})
    resp = client.chat.completions.create(model=model, messages=messages, **token_kwargs)
    elapsed = round((time.time() - t0) * 1000)
    return resp.choices[0].message.content or "", elapsed


def _judge(judge_client: OpenAI, prompt: dict, response: str) -> dict:
    user_msg = (
        f"[프롬프트 ID] {prompt['id']}\n"
        f"[기대 형식] {prompt['expected_format']}\n"
        f"[제공된 데이터] {prompt['provided_data']}\n\n"
        f"[평가할 응답]\n{response}"
    )
    token_kwargs = ({"max_completion_tokens": 4000} if _uses_completion_tokens(JUDGE_MODEL)
                    else {"max_tokens": 600})
    resp = judge_client.chat.completions.create(
        model=JUDGE_MODEL,
        messages=[{"role": "system", "content": JUDGE_SYSTEM},
                  {"role": "user",   "content": user_msg}],
        response_format={"type": "json_object"},
        **token_kwargs,
    )
    raw = resp.choices[0].message.content or ""
    try:
        return json.loads(raw)
    except Exception:
        start = raw.find("{")
        end   = raw.rfind("}") + 1
        try:
            return json.loads(raw[start:end])
        except Exception:
            return {"korean": 0, "format": 0, "grounding": 0, "reasoning": 0, "actionability": 0, "comment": f"파싱 실패: {raw[:60]}"}


def _bar(score: int, max_score=10) -> str:
    filled = round(score / 2)   # 10점 → 5칸 바
    return "█" * filled + "░" * (5 - filled)


def run(fast_only: bool = False, quality_only: bool = False, out_json: Path | None = None, out_md: Path | None = None, run_id: str | None = None):
    model     = os.getenv("LLM_MODEL_FAST", "exaone3.5:7.8b") if fast_only else MODEL
    role_label = "fast (EXAONE)" if fast_only else ("quality (Gemma4)" if quality_only else "all")

    if fast_only:
        prompts = [p for p in PROMPTS if p.get("role") == "fast"]
    elif quality_only:
        prompts = [p for p in PROMPTS if p.get("role") != "fast"]
    else:
        prompts = PROMPTS

    print(f"\n{'='*70}")
    print(f"  sLLM 성능 평가  |  모델: {model}  |  프로바이더: {PROVIDER}")
    print(f"  역할: {role_label}  |  문항 수: {len(prompts)}")
    print(f"  심사위원: {JUDGE_MODEL}  |  {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"{'='*70}\n")

    test_client  = _make_client(PROVIDER)
    judge_client = _make_client("openai")

    AXES = ["korean", "format", "grounding", "reasoning", "actionability"]
    results = []
    for p in prompts:
        print(f"▶ [{p['id']}] {p['name']} ...", end=" ", flush=True)
        response, elapsed_ms = _call(test_client, model, p["messages"])
        scores = _judge(judge_client, p, response)
        # Some local judges emit partial or malformed JSON. Keep the run alive
        # and mark missing axes as zero instead of aborting the whole benchmark.
        for ax in AXES:
            try:
                scores[ax] = int(scores.get(ax, 0))
            except (TypeError, ValueError):
                scores[ax] = 0
        scores.setdefault("comment", "")
        scores["elapsed_ms"] = elapsed_ms
        scores["response"]   = response
        results.append({"prompt": p["id"], "name": p["name"], **scores})

        avg = round(sum(scores.get(ax, 0) for ax in AXES) / len(AXES), 1)
        print(f"완료 ({elapsed_ms}ms) — 평균 {avg}/10")

    AXES = ["korean", "format", "grounding", "reasoning", "actionability"]
    LABELS = {"korean": "한국어", "format": "형식", "grounding": "근거성",
              "reasoning": "논리성", "actionability": "실용성"}

    # ── 결과 테이블 ─────────────────────────────────────────────────
    print(f"\n{'─'*80}")
    print(f"  {'프롬프트':<18} {'한국어':^8} {'형식':^8} {'근거성':^8} {'논리성':^8} {'실용성':^8} {'속도':^8} {'평균':^6}")
    print(f"{'─'*80}")
    scores_sum = {ax: [] for ax in AXES}
    for r in results:
        avg = round(sum(r.get(ax, 0) for ax in AXES) / len(AXES), 1)
        print(
            f"  {r['name']:<18} "
            + "".join(f"{_bar(r.get(ax,0)):^8}" for ax in AXES)
            + f"{r['elapsed_ms']:>5}ms  "
            f"{avg:>4.1f}"
        )
        print(f"  {'':18} " + " ".join(f"{r.get(ax,0)}/10{' ':2}" for ax in AXES))
        print(f"  {'':18} 💬 {r['comment']}")
        print()
        for ax in AXES:
            scores_sum[ax].append(r.get(ax, 0))

    avgs = {ax: round(sum(scores_sum[ax]) / len(results), 1) for ax in AXES}
    total = round(sum(avgs.values()) / len(AXES), 1)

    print(f"{'─'*80}")
    print(f"  {'전체 평균':<18} " + "".join(f"{avgs[ax]:^8.1f}" for ax in AXES) + f"{'':8} {total:^6.1f}")
    print(f"{'─'*80}\n")

    # 개선 포인트 요약
    weak = sorted(results, key=lambda r: sum(r.get(ax,0) for ax in AXES) / len(AXES))[:3]
    print("⚠️  우선 개선 대상 (하위 3개):")
    for r in weak:
        avg = round(sum(r.get(ax,0) for ax in AXES) / len(AXES), 1)
        print(f"   • [{r['prompt']}] 평균 {avg}/10 — {r['comment']}")

    # ── 공통 metrics schema 저장 ───────────────────────────────────────
    if out_json is None or out_md is None:
        default_json, default_md = default_output_paths(TEST_ID, run_id, suffix=model)
        out_json = out_json or default_json
        out_md = out_md or default_md

    elapsed_values = [float(r.get("elapsed_ms", 0.0)) for r in results]
    total_llm_ms = round(sum(elapsed_values), 2)
    avg_llm_ms = round(total_llm_ms / len(elapsed_values), 2) if elapsed_values else 0.0
    summary = {
        "model": model,
        "provider": PROVIDER,
        "judge": JUDGE_MODEL,
        "role": role_label,
        **avgs,
        "total": total,
        "prompt_count": len(prompts),
        "avg_elapsed_ms": avg_llm_ms,
        "total_elapsed_ms": total_llm_ms,
    }
    metrics = build_metrics_envelope(
        test_id=TEST_ID,
        run_id=infer_run_id(out_json),
        metric_family=METRIC_FAMILY,
        dataset_path="dev/eval/harness.py::PROMPTS",
        dataset_count=len(prompts),
        phase_latency_ms={"answer": total_llm_ms, "qa": total_llm_ms, "total": total_llm_ms},
        component_latency_ms={"llm": total_llm_ms, "api": total_llm_ms, "total": total_llm_ms},
        payload_metrics={
            "prompt_count": len(prompts),
            "response_characters": sum(len(str(r.get("response", ""))) for r in results),
        },
        summary=summary,
        gates={"total_score_min_8_0": total >= 8.0},
        errors=[r for r in results if any(int(r.get(ax, 0)) <= 0 for ax in AXES)],
        details={"results": results},
    )
    write_json(out_json, metrics)
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text(
        "\n".join([
            "# Test 07 — LLM answer gate",
            "",
            f"> model: `{model}` | provider: `{PROVIDER}` | judge: `{JUDGE_MODEL}` | prompts: {len(prompts)}",
            "",
            "## Summary",
            "",
            "| metric | value |",
            "|---|---:|",
            *[f"| {ax} | {avgs[ax]} |" for ax in AXES],
            f"| total | {total} |",
            f"| avg_elapsed_ms | {avg_llm_ms} |",
            "",
            "## Weak prompts",
            "",
            *[f"- `{r['prompt']}`: {round(sum(r.get(ax,0) for ax in AXES) / len(AXES), 1)}/10 — {r['comment']}" for r in weak],
            "",
        ]) + "\n",
        encoding="utf-8",
    )
    print(f"\n💾 metrics 저장: {out_json}")
    print(f"💾 report 저장: {out_md}")
    print()


